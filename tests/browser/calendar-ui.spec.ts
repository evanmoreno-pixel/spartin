import AxeBuilder from '@axe-core/playwright'
import { expect, test, type APIRequestContext, type Page } from '@playwright/test'
import { selectDemoAccount, startBrowserApp, stubStreetTiles } from './localApp'

let app: Awaited<ReturnType<typeof startBrowserApp>>
test.beforeEach(async () => { app = await startBrowserApp() })
test.afterEach(async () => { await app?.stop() })

async function signIn(page: Page, name = 'Participant 1') {
  await stubStreetTiles(page)
  await page.goto(app.url)
  await selectDemoAccount(page, name)
}

async function signInOrganizer(request: APIRequestContext) {
  const response = await request.post(`${app.url}/api/session`, { data: { accountKey: 'organizer-1' } })
  expect(response.ok()).toBe(true)
}

async function createEvent(request: APIRequestContext, title: string, startTime: string, endTime: string, status = 'scheduled') {
  const response = await request.post(`${app.url}/api/events`, { data: { title, startTime, endTime, location: 'Student Union', status } })
  expect(response.status()).toBe(201)
  return (await response.json()).data.eventId as string
}

test('calendar desktop views, keyboard activation, local dates and original event details', async ({ page, request }) => {
  await signInOrganizer(request)
  const id = await createEvent(request, 'Fall Clock Change Workshop', '2096-11-04T08:30:00Z', '2096-11-04T09:30:00Z')
  await createEvent(request, 'Overnight Campus Session', '2096-11-04T06:30:00Z', '2096-11-04T07:45:00Z')
  await signIn(page)
  await page.clock.setFixedTime(new Date('2096-11-04T20:00:00Z'))
  await page.getByRole('link', { name: 'Calendar', exact: true }).click()
  const month = page.getByRole('table', { name: 'November 2096' })
  await expect(month).toBeVisible()
  await expect(month.getByRole('columnheader')).toHaveCount(7)
  await expect(month.getByRole('button', { name: /Saturday, November 3, 2096, 1 event/ })).toBeVisible()
  const today = month.getByRole('button', { name: /Sunday, November 4, 2096, 2 events/ })
  await expect(today).toHaveAttribute('aria-current', 'date')
  await expect(month.getByRole('link', { name: 'Overnight Campus Session' })).toHaveCount(2)

  const previous = page.getByRole('button', { name: 'Previous month' })
  await previous.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('table', { name: 'October 2096' })).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Today', exact: true })).toBeFocused()
  await page.keyboard.press('Space')
  await expect(month).toBeVisible()

  await page.getByRole('button', { name: 'Week', exact: true }).click()
  const sunday = page.getByRole('button', { name: /Open Sunday, November 4, 2096/ })
  const saturday = page.getByRole('button', { name: /Open Saturday, November 10, 2096/ })
  await expect(saturday).toBeVisible()
  const sundayBox = await sunday.boundingBox()
  const saturdayBox = await saturday.boundingBox()
  expect(sundayBox!.y).toBe(saturdayBox!.y)
  expect(saturdayBox!.x).toBeGreaterThan(sundayBox!.x)
  await sunday.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Sunday, November 4, 2096' })).toBeFocused()
  const workshop = page.getByRole('listitem').filter({ hasText: 'Fall Clock Change Workshop' })
  await expect(workshop.locator('time')).toHaveText(['1:30 AM PDT', '1:30 AM PST'])
  await expect(workshop.getByText('Student Union')).toBeVisible()
  await workshop.getByRole('link').click()
  await expect(page).toHaveURL(`${app.url}/participant/events/${id}`)
  await expect(page.getByRole('heading', { name: 'Fall Clock Change Workshop' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Join', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Pass', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Directions' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Share event' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Add to Google Calendar' })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Calendar' }).click()
  await expect(page.getByRole('button', { name: 'Day', exact: true })).toHaveAttribute('aria-pressed', 'true')

  await page.getByRole('button', { name: 'Year', exact: true }).click()
  await expect(page.getByRole('table')).toHaveCount(12)
  const november = page.getByRole('table', { name: 'November' })
  await expect(november.getByRole('cell', { name: 'Sunday, November 4, 2096, 2 events' })).toBeVisible()
  await page.getByRole('button', { name: 'November', exact: true }).click()
  await expect(month).toBeVisible()
  const check = await new AxeBuilder({ page }).include('.calendar-page').withTags(['wcag2a', 'wcag2aa']).analyze()
  expect(check.violations).toEqual([])
})

test('calendar fits narrow touch screens and exposes the selected day agenda', async ({ browser, request }) => {
  await signInOrganizer(request)
  await createEvent(request, 'Mobile Study Session', '2096-02-29T20:00:00Z', '2096-02-29T22:00:00Z')
  const mobile = await browser.newPage({ viewport: { width: 320, height: 740 }, hasTouch: true, timezoneId: 'America/Los_Angeles' })
  try {
    await signIn(mobile)
    await mobile.getByRole('link', { name: 'Calendar', exact: true }).tap()
    await mobile.goto(`${app.url}/participant/calendar?date=2096-02-01`)
    const fits = async () => expect(await mobile.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
    const month = mobile.getByRole('table', { name: 'February 2096' })
    await expect(month).toBeVisible()
    await fits()
    const date = month.getByRole('button', { name: /February 29, 2096, 1 event/ })
    await expect(date.locator('.calendar-cell-count')).toHaveText('1')
    await date.tap()
    await expect(date).toHaveAttribute('aria-pressed', 'true')
    const selected = mobile.getByRole('region', { name: /February 29, 2096/ })
    await expect(selected.getByText('12:00 PM', { exact: true })).toBeVisible()
    await expect(selected.getByText('2:00 PM', { exact: true })).toBeVisible()
    await mobile.getByRole('button', { name: 'Week', exact: true }).tap()
    const first = mobile.getByRole('button', { name: /^Open Sunday/ })
    const second = mobile.getByRole('button', { name: /^Open Monday/ })
    await expect(first).toBeVisible()
    expect((await second.boundingBox())!.y).toBeGreaterThan((await first.boundingBox())!.y)
    await fits()
    await mobile.getByRole('button', { name: 'Day', exact: true }).tap()
    await fits()
    await mobile.getByRole('link', { name: 'Mobile Study Session' }).tap()
    await expect(mobile.getByRole('heading', { name: 'Mobile Study Session' })).toBeVisible()
    await mobile.getByRole('link', { name: 'Back to Calendar' }).tap()
    await mobile.getByRole('button', { name: 'Year', exact: true }).tap()
    await expect(mobile.getByRole('table')).toHaveCount(12)
    await fits()
  } finally {
    await mobile.close()
  }
})

test('calendar refresh reads organizer CRUD and participant visibility from real SQLite', async ({ page, browser, request }) => {
  expect((await request.get(`${app.url}/api/events`)).status()).toBe(401)
  const organizer = await browser.newPage({ timezoneId: 'America/Los_Angeles' })
  const calendarUrl = `${app.url}/participant/calendar?date=2099-04-12`
  const title = 'Calendar Integration Study Group'
  try {
    await signIn(page)
    await page.goto(calendarUrl)
    const month = page.getByRole('table', { name: 'April 2099' })
    const count = (day: number, events: number) => month.getByRole('button', { name: new RegExp(`April ${day}, 2099, ${events} event`) })
    await expect(count(12, 0)).toBeVisible()
    expect((await page.request.get(`${app.url}/api/organizer/events`)).status()).toBe(403)
    await signIn(organizer, 'Organizer 1')
    const start = organizer.getByLabel('Start date and time')
    const end = organizer.getByLabel('End date and time')
    const refresh = () => page.getByRole('button', { name: 'Refresh events' }).click()
    const edit = () => organizer.getByRole('link', { name: 'Edit or reschedule' }).click()
    const save = () => organizer.getByRole('button', { name: 'Save changes' }).click()
    await organizer.getByRole('link', { name: 'Create event' }).click()
    await organizer.getByLabel('Event title').fill(title)
    await organizer.getByLabel('Location', { exact: true }).fill('Student Union')
    await start.fill('2099-04-12T14:00')
    await end.fill('2099-04-12T15:00')
    await organizer.getByRole('button', { name: 'Create event', exact: true }).click()
    await expect(organizer.getByText('Event created.', { exact: true })).toBeVisible()
    const id = new URL(organizer.url()).pathname.split('/').at(-1)!
    const storedEvent = app.db.prepare('SELECT start_time, status FROM events WHERE event_id = ?')
    expect(storedEvent.get(id)).toMatchObject({ start_time: '2099-04-12T21:00:00.000Z', status: 'scheduled' })
    await refresh()
    await expect(count(12, 1)).toBeVisible()

    await edit()
    await start.fill('2099-04-13T16:00')
    await end.fill('2099-04-13T17:00')
    await save()
    await expect(organizer.getByText('Event rescheduled.', { exact: true })).toBeVisible()
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(count(12, 0)).toBeVisible()
    await count(13, 1).click()
    const selection = page.getByRole('region', { name: /April 13, 2099/ })
    await expect(selection.getByText('4:00 PM', { exact: true })).toBeVisible()

    await edit()
    await organizer.getByLabel('Status').selectOption('postponed')
    await save()
    await expect(organizer.getByText('Event postponed.', { exact: true })).toBeVisible()
    await refresh()
    await expect(count(13, 0)).toBeVisible()
    expect((await page.request.get(`${app.url}/api/events/${id}`)).status()).toBe(404)
    expect(storedEvent.get(id)).toMatchObject({ status: 'postponed' })

    await signInOrganizer(request)
    const endedId = await createEvent(request, 'Already Ended', '2020-01-01T20:00:00Z', '2020-01-01T21:00:00Z')
    await page.goto(`${app.url}/participant/calendar?date=2020-01-01`)
    await expect(page.getByRole('region', { name: /January 1, 2020/ }).getByText('No events scheduled.')).toBeVisible()
    expect((await page.request.get(`${app.url}/api/events/${endedId}`)).status()).toBe(404)
    await page.goto(calendarUrl)

    await edit()
    await organizer.getByLabel('Status').selectOption('scheduled')
    await save()
    await expect(organizer.getByText('Event updated.', { exact: true })).toBeVisible()
    await refresh()
    await expect(count(13, 1)).toBeVisible()
    await organizer.getByRole('button', { name: 'Delete', exact: true }).click()
    await organizer.getByRole('dialog').getByRole('button', { name: 'Delete event' }).click()
    await expect(organizer.getByText('Event deleted.', { exact: true })).toBeVisible()
    await refresh()
    await expect(count(13, 0)).toBeVisible()
    await expect(month.getByRole('link', { name: title })).toHaveCount(0)
    expect(storedEvent.get(id)).toBeUndefined()
  } finally {
    await organizer.close()
  }
})
